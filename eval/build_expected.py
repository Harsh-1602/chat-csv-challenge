"""Compute expected answers for the eval question sets and score relationship detection.

Loads each dataset's CSVs exactly like the app does (app.profiling), runs every gold SQL query
in DuckDB, and writes:
  eval/expected/<dataset>.json   machine-readable expected results
  eval/expected/SUMMARY.md       human-readable questions, SQL and outputs

Usage (from the repo root, after fetch_datasets.py):
    backend\\.venv\\Scripts\\python.exe eval\\build_expected.py
"""

from __future__ import annotations

import datetime as dt
import decimal
import json
import sys
import tempfile
from pathlib import Path
from typing import Any

import duckdb

EVAL_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(EVAL_DIR.parent / "backend"))

from app.profiling import profile_dataset, safe_table_name  # noqa: E402

QUESTIONS_DIR = EVAL_DIR / "questions"
DATASETS_DIR = EVAL_DIR / "datasets"
EXPECTED_DIR = EVAL_DIR / "expected"
MAX_PREVIEW_ROWS = 10


def _json_value(value: Any) -> Any:
    if isinstance(value, (dt.datetime, dt.date)):
        return value.isoformat()
    if isinstance(value, decimal.Decimal):
        return float(value)
    if isinstance(value, float):
        return round(value, 6)
    return value


def _relationship_key(text: str) -> tuple[str, str]:
    table, column = text.split(".", 1)
    return table.lower(), column.lower()


def _score_relationships(expected: list[dict], detected: list) -> dict:
    truth = {(_relationship_key(r["from"]), _relationship_key(r["to"])) for r in expected}
    found = {
        ((r.from_table.lower(), r.from_column.lower()), (r.to_table.lower(), r.to_column.lower())) for r in detected
    }
    hits = truth & found

    def fmt(pairs: set) -> list[str]:
        return sorted(f"{a[0]}.{a[1]} -> {b[0]}.{b[1]}" for a, b in pairs)

    return {
        "expected": len(truth),
        "detected": len(found),
        "correct": len(hits),
        "precision": round(len(hits) / len(found), 3) if found else None,
        "recall": round(len(hits) / len(truth), 3) if truth else None,
        "missed": fmt(truth - found),
        "false_positives": fmt(found - truth),
    }


def build_dataset(spec_path: Path) -> dict:
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    data_dir = DATASETS_DIR / spec["dataset"]
    csv_files = sorted(data_dir.glob("*.csv"))
    if not csv_files:
        raise SystemExit(f"No CSVs in {data_dir}. Run eval/fetch_datasets.py first.")

    used: set[str] = set()
    files = [(p.name, safe_table_name(p.name, used), p, p.stat().st_size) for p in csv_files]

    with tempfile.TemporaryDirectory() as tmp:
        db_path = Path(tmp) / "dataset.duckdb"
        profile = profile_dataset(db_path, files, lambda *_: None)
        results = []
        with duckdb.connect(str(db_path), read_only=True) as con:
            for question in spec["questions"]:
                entry = {k: v for k, v in question.items()}
                if question.get("gold_sql"):
                    cursor = con.execute(question["gold_sql"])
                    columns = [d[0] for d in cursor.description]
                    rows = [[_json_value(v) for v in row] for row in cursor.fetchall()]
                    entry["expected"] = {"columns": columns, "rows": rows, "row_count": len(rows)}
                else:
                    entry["expected"] = None
                results.append(entry)

    return {
        "dataset": spec["dataset"],
        "description": spec["description"],
        "source": spec["source"],
        "license": spec["license"],
        "tables": {t.table_name: t.row_count for t in profile.tables},
        "total_rows": profile.total_rows,
        "relationship_detection": _score_relationships(spec["relationships"], profile.relationships),
        "questions": results,
    }


def _markdown_table(columns: list[str], rows: list[list[Any]]) -> list[str]:
    def cell(value: Any) -> str:
        return "NULL" if value is None else str(value).replace("|", "\\|")

    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows[:MAX_PREVIEW_ROWS]]
    if len(rows) > MAX_PREVIEW_ROWS:
        lines.append(f"\n_…{len(rows) - MAX_PREVIEW_ROWS} more rows_")
    return lines


def render_summary(builds: list[dict]) -> str:
    out = [
        "# Expected answers (generated)",
        "",
        "Generated by `eval/build_expected.py` from the gold SQL in `eval/questions/`. Do not edit by hand.",
        "",
        "## Relationship detection by the current profiler",
        "",
        "| Dataset | Expected | Detected | Correct | Precision | Recall |",
        "|---|---|---|---|---|---|",
    ]
    for b in builds:
        r = b["relationship_detection"]
        out.append(
            f"| {b['dataset']} | {r['expected']} | {r['detected']} | {r['correct']} | {r['precision']} | {r['recall']} |"
        )
    for b in builds:
        r = b["relationship_detection"]
        out += ["", f"## {b['dataset']}", "", f"{b['description']}", "",
                f"Source: {b['source']} · License: {b['license']} · {len(b['tables'])} tables, {b['total_rows']:,} rows", ""]
        if r["missed"]:
            out.append("Missed relationships: " + ", ".join(f"`{m}`" for m in r["missed"]))
        if r["false_positives"]:
            out.append("False-positive relationships: " + ", ".join(f"`{m}`" for m in r["false_positives"]))
        for q in b["questions"]:
            context = f" (follow-up to {', '.join(q['context'])})" if q.get("context") else ""
            out += ["", f"### {q['id']} — {q['question']}{context}", "",
                    f"*Category:* {q['category']} · *Expected:* {q['expected_type']}"
                    + (f" ({q['chart']['type']} chart, x={q['chart']['x']}, y={q['chart']['y']})" if q.get("chart") else "")]
            if q.get("notes"):
                out.append(f"\n*Notes:* {q['notes']}")
            if q["expected"]:
                out += ["", "```sql", q["gold_sql"], "```", ""]
                out += _markdown_table(q["expected"]["columns"], q["expected"]["rows"])
    return "\n".join(out) + "\n"


def main() -> None:
    EXPECTED_DIR.mkdir(exist_ok=True)
    builds = []
    for spec_path in sorted(QUESTIONS_DIR.glob("*.json")):
        build = build_dataset(spec_path)
        (EXPECTED_DIR / f"{build['dataset']}.json").write_text(json.dumps(build, indent=2), encoding="utf-8")
        answered = sum(1 for q in build["questions"] if q["expected"] is not None)
        rel = build["relationship_detection"]
        print(
            f"{build['dataset']}: {len(build['questions'])} questions ({answered} with SQL answers); "
            f"relationships {rel['correct']}/{rel['expected']} found, {len(rel['false_positives'])} false positives"
        )
        builds.append(build)
    (EXPECTED_DIR / "SUMMARY.md").write_text(render_summary(builds), encoding="utf-8")
    print(f"Wrote {EXPECTED_DIR}")


if __name__ == "__main__":
    main()
